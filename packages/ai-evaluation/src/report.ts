/**
 * The bake-off report for one model (ENG-21): the scorecard as Markdown for people and as the
 * evaluation records it would produce.
 *
 * Why this exists: the plan's acceptance is "a bake-off report exists for each candidate model and
 * is recorded". This is the report; `ai:bake-off-import` is the recording. It contains metrics,
 * counts and case ids — never reply text, which stays in the results file.
 */
import { costTasks, describeCostAssumptions } from './cost.js';
import type { Scorecard } from './score.js';

const percent = (value: number): string => `${(value * 100).toFixed(2)} %`;

function formatValue(name: string, value: number): string {
  if (name.endsWith('_rate')) return percent(value);
  if (name.endsWith('_ms')) return `${Math.round(value)} ms`;
  if (name.endsWith('_inr')) return `Rs ${value.toFixed(2)}`;
  return String(value);
}

export function renderReport(card: Scorecard, input: { readonly resultsSha256: string; readonly startedAt: string; readonly reviewed: boolean }): string {
  const lines: string[] = [];
  lines.push(`# Bake-off report — ${card.model}`);
  lines.push('');
  lines.push(`Evaluation set \`${card.setKey}\` v${card.setVersion}; checks \`${card.checksVersion}\`; provider \`${card.providerKey}\`; run started ${input.startedAt}.`);
  lines.push(`Results file SHA-256 \`${input.resultsSha256}\`. Human review: ${input.reviewed ? 'supplied' : '**not supplied** — no feature that needs one can PASS'}.`);
  lines.push('');
  lines.push('Generated by `packages/ai-evaluation` from the raw replies; recorded only by `ai:bake-off-import`.');
  lines.push('');
  for (const feature of card.features) {
    lines.push(`## \`${feature.featureKey}\` — prompt \`${feature.promptKey}\` v${feature.promptVersion}: **${feature.decision}**`);
    lines.push('');
    lines.push(`${feature.cases} cases; latency p50 ${feature.latency.p50} ms, p95 ${feature.latency.p95} ms; mean tokens ${feature.tokens.promptMean} in / ${feature.tokens.completionMean} out.`);
    lines.push('');
    lines.push('| Metric | Value | Threshold | Met |');
    lines.push('| --- | --- | --- | --- |');
    for (const metric of feature.metrics) {
      lines.push(`| \`${metric.name}\` | ${formatValue(metric.name, metric.value)} | ${metric.comparator === 'AT_LEAST' ? '≥' : '≤'} ${formatValue(metric.name, metric.threshold)} | ${metric.met ? 'yes' : '**no**'} |`);
    }
    for (const missing of feature.missingHumanMetrics) lines.push(`| \`${missing}\` | NA (no review sheet) | — | **no** |`);
    lines.push('');
    const failing = card.cases.filter((entry) => entry.task === feature.task && !entry.passed);
    if (failing.length) {
      lines.push(`Cases that did not meet their expectation (${failing.length}): ${failing.map((entry) => `\`${entry.id}\`${entry.error ? ` (${entry.error})` : entry.leak ? ' (leak)' : entry.unsafe ? ' (unsafe)' : ''}`).join(', ')}.`);
      lines.push('');
    }
  }
  lines.push('## Cost');
  lines.push('');
  lines.push(`Estimated **Rs ${card.cost.inrPerStudentMonth.toFixed(2)} per active student per month** against the plan's Rs 10. Pod seconds per request (measured): ${Object.entries(card.cost.secondsPerRequest).map(([task, seconds]) => `${task} ${seconds} s`).join(', ')}.`);
  lines.push('');
  lines.push(`Assumptions (not measurements): ${describeCostAssumptions(card.cost.assumptions, costTasks(card.cost))}.`);
  lines.push('');
  return `${lines.join('\n')}\n`;
}
