// Generates the Momentum icon data and hover-motion stylesheet from the copied icon library.
//
// The approved icons live in src/assets/one/icons (copied, unchanged, from the design
// inventory). This script turns them into src/icons/iconData.ts, which the <Icon> component
// renders inline, and src/styles/icon-motion.css, the play-once hover cues for module icons.
// Inlining keeps every icon in the bundle: no network fetch per icon, no external sprite
// that cannot take the per-instance gradient. Re-run after changing the copied SVGs:
//   node apps/web/scripts/build-icons.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(web, 'src/assets/one/icons');
const iconMap = JSON.parse(readFileSync(join(source, 'icon-map.json'), 'utf8'));
const utilityNames = new Set(Object.values(iconMap.utility));

const reactAttr = {
  class: 'className', 'fill-rule': 'fillRule', 'clip-rule': 'clipRule', 'stroke-width': 'strokeWidth',
  'stroke-linejoin': 'strokeLinejoin', 'stroke-linecap': 'strokeLinecap', 'stroke-dasharray': 'strokeDasharray',
  'stroke-dashoffset': 'strokeDashoffset', maskUnits: 'maskUnits',
};
const allowedTags = new Set(['path', 'g', 'defs', 'mask', 'rect', 'polyline', 'circle']);

/** A minimal parser for the generator's own uniform SVG output (no text nodes, no CDATA). */
function parse(markup) {
  const body = markup.replace(/<style>[\s\S]*?<\/style>/g, '').replace(/<\?xml[^>]*>/g, '');
  const root = { tag: 'root', attrs: {}, children: [] };
  const stack = [root];
  const tagRe = /<(\/?)([a-zA-Z]+)([^>]*?)(\/?)>/g;
  let match;
  while ((match = tagRe.exec(body))) {
    const [, closing, tag, rawAttrs, selfClosing] = match;
    if (tag === 'svg') continue;
    if (!allowedTags.has(tag)) throw new Error(`unexpected <${tag}>`);
    if (closing) { stack.pop(); continue; }
    const attrs = {};
    for (const [, key, value] of rawAttrs.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)) attrs[key] = value;
    const node = { tag, attrs, children: [] };
    stack.at(-1).children.push(node);
    if (!selfClosing) stack.push(node);
  }
  return root.children;
}

function normalise(nodes) {
  return nodes.map((node) => {
    const classes = new Set((node.attrs.class ?? '').split(/\s+/).filter(Boolean));
    const attrs = {};
    for (const [key, value] of Object.entries(node.attrs)) {
      if (key === 'class') continue;
      // Static files carry the second tone as opacity=".42"; mark it so the active state can raise it.
      if (key === 'opacity' && value === '.42') { classes.add('s'); continue; }
      attrs[reactAttr[key] ?? key] = value;
    }
    // The second tone and the hidden motion helpers are attributes too, so the icon renders
    // correctly even before (or without) the stylesheet; CSS only overrides them.
    if (classes.has('s')) attrs.opacity = '.42';
    if (classes.has('p-turn') || classes.has('p-dB')) attrs.opacity = '0';
    if (classes.has('p-chk')) { attrs.strokeDasharray = '12'; attrs.strokeDashoffset = '0'; }
    classes.delete('f');
    if (classes.size) attrs.className = [...classes].join(' ');
    const children = normalise(node.children);
    return children.length ? [node.tag, attrs, children] : [node.tag, attrs];
  });
}

const staticNames = readdirSync(join(source, 'svg')).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).sort();
const animatedNames = new Set(readdirSync(join(source, 'animated')).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)));

const data = {};
const keyframes = new Map();
const motionRules = [];
for (const name of staticNames) {
  // Module icons come from their animated file: same geometry, plus the part classes the
  // hover cue animates. Utility icons never animate in product UI, so they use the static file.
  const moving = animatedNames.has(name) && !utilityNames.has(name);
  const markup = readFileSync(join(source, moving ? 'animated' : 'svg', `${name}.svg`), 'utf8');
  data[name] = normalise(parse(markup));
  if (!moving) continue;
  for (const [, frameName, frames] of markup.matchAll(/@keyframes (\w+)(\{(?:[^{}]*\{[^{}]*\})*[^{}]*\})/g)) {
    const previous = keyframes.get(frameName);
    if (previous && previous !== frames) throw new Error(`conflicting @keyframes ${frameName}`);
    keyframes.set(frameName, frames);
  }
  for (const [, part, declarations] of markup.matchAll(/\.ai-loop \.(p-[\w-]+)\{([^}]*)\}/g)) {
    const once = declarations.replace(/ infinite;/, ' 1;');
    motionRules.push(`.one-icon-host:is(:hover, :focus-visible, [aria-current="page"]) .one-icon--motion.ai-${name} .${part} { ${once} }`);
  }
}

const header = '// Generated by apps/web/scripts/build-icons.mjs from src/assets/one/icons. Do not edit by hand.\n';
const names = Object.keys(data);
const ts = `${header}// The Momentum icon set as element trees: [tag, attributes, children?]. Ids are local and are
// prefixed per rendered instance, so masks and gradients never collide on a page.
export type IconNode = readonly [tag: string, attrs: Readonly<Record<string, string>>, children?: readonly IconNode[]];

export const iconNames = ${JSON.stringify(names)} as const;

export type IconName = (typeof iconNames)[number];

/** Utility icons: controls and inline glyphs. They never carry a hover animation. */
export const utilityIconNames: ReadonlySet<IconName> = new Set<IconName>(${JSON.stringify(names.filter((n) => utilityNames.has(n)))});

export const iconData: Readonly<Record<IconName, readonly IconNode[]>> = ${JSON.stringify(data)};
`;
writeFileSync(join(web, 'src/icons/iconData.ts'), ts);

const css = `/* Generated by apps/web/scripts/build-icons.mjs from src/assets/one/icons. Do not edit by hand.
 * Play-once hover cues for Momentum module icons (nav and module tiles only, never utility icons).
 * A cue plays when its host (.one-icon-host: a nav item or tile) is hovered, focused, or becomes
 * the current page. Under prefers-reduced-motion the icon stays static. */
@media (prefers-reduced-motion: no-preference) {
${[...keyframes].map(([n, f]) => `@keyframes ${n}${f}`).join('\n')}
${motionRules.join('\n')}
}
`;
writeFileSync(join(web, 'src/styles/icon-motion.css'), css);
console.log(`${names.length} icons, ${motionRules.length} motion rules, ${keyframes.size} keyframes`);
