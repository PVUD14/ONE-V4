-- Allow the storage layer to hold a system-generated export bundle.
--
-- The allowlist exists in two places on purpose. This constraint is the storage-level
-- gate and now admits application/json so a data export can be stored like any other
-- file, inheriting the same containment, checksum and retention behaviour.
--
-- The upload endpoint keeps its own, narrower list and still refuses application/json,
-- so widening this does not let a student upload JSON. Only the export writer, which
-- produces the bytes itself, uses the new type.

ALTER TABLE stored_files DROP CONSTRAINT IF EXISTS stored_files_content_type_ck;
ALTER TABLE stored_files ADD CONSTRAINT stored_files_content_type_ck CHECK (content_type IN (
  'application/pdf',
  'image/png',
  'image/jpeg',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  'application/json'
));

-- Export bundles are produced by the platform, not uploaded, so they are never
-- scanned by an external engine. Recording the producer keeps 'CLEAN' honest: it
-- means "generated by us", not "checked by a scanner that never ran".
ALTER TABLE stored_files ADD COLUMN IF NOT EXISTS system_generated boolean NOT NULL DEFAULT false;
ALTER TABLE stored_files DROP CONSTRAINT IF EXISTS stored_files_system_generated_ck;
ALTER TABLE stored_files ADD CONSTRAINT stored_files_system_generated_ck CHECK (
  system_generated = false OR content_type = 'application/json'
);
